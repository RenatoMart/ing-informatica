-- ---------- [EXTRA] sesiones de Laravel (driver database) ----------
CREATE TABLE IF NOT EXISTS sessions (
    id            VARCHAR(255) PRIMARY KEY,
    user_id       BIGINT NULL,
    ip_address    VARCHAR(45) NULL,
    user_agent    TEXT NULL,
    payload       TEXT NOT NULL,
    last_activity INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_id_index       ON sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_last_activity_index ON sessions(last_activity);

-- ---------- [EXTRA] tokens de recuperacion de contrasena (P5) ----------
CREATE TABLE IF NOT EXISTS token_recuperacion (
    id_token       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INTEGER NOT NULL REFERENCES usuario(id_usuario),
    token_hash     CHAR(64) NOT NULL UNIQUE,
    fecha_expira   TIMESTAMP NOT NULL,
    fecha_uso      TIMESTAMP NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_token_recuperacion_usuario ON token_recuperacion(id_usuario);

-- ---------- [EXTRA] historial completo de revision ----------
CREATE TABLE IF NOT EXISTS historial_revision (
    id_historial    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad         VARCHAR(20) NOT NULL
                    CHECK (entidad IN ('publicacion','docente','plan','documento','campana')),
    id_registro     INTEGER NOT NULL,
    accion          VARCHAR(30) NOT NULL,
    estado_anterior VARCHAR(30) NULL,
    estado_nuevo    VARCHAR(30) NOT NULL,
    id_usuario      INTEGER NULL REFERENCES usuario(id_usuario),  -- NULL = sistema
    observaciones   VARCHAR(500) NULL,
    fecha           TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_historial_revision_registro ON historial_revision(entidad, id_registro);
CREATE INDEX IF NOT EXISTS ix_historial_revision_usuario  ON historial_revision(id_usuario);

-- ---------- [EXTRA] columnas anadidas a tablas del diccionario ----------
ALTER TABLE usuario           ADD COLUMN IF NOT EXISTS cargo VARCHAR(100) NULL;
ALTER TABLE bitacora_acceso   ADD COLUMN IF NOT EXISTS id_usuario_actor INTEGER NULL REFERENCES usuario(id_usuario),
                              ADD COLUMN IF NOT EXISTS ip VARCHAR(45) NULL;
ALTER TABLE solicitud_acceso  ADD COLUMN IF NOT EXISTS correo_solicitado VARCHAR(150) NULL,
                              ADD COLUMN IF NOT EXISTS id_usuario_objetivo INTEGER NULL REFERENCES usuario(id_usuario),
                              ADD COLUMN IF NOT EXISTS observacion_resolucion VARCHAR(255) NULL,
                              ADD COLUMN IF NOT EXISTS fecha_ejecucion TIMESTAMP NULL;
ALTER TABLE departamento      ADD COLUMN IF NOT EXISTS correo VARCHAR(150) NULL;
ALTER TABLE publicacion       ADD COLUMN IF NOT EXISTS operacion_pendiente VARCHAR(10) NULL
                                  CHECK (operacion_pendiente IN ('cambio','baja')),
                              ADD COLUMN IF NOT EXISTS cambios_pendientes JSONB NULL;
ALTER TABLE docente           ADD COLUMN IF NOT EXISTS operacion_pendiente VARCHAR(10) NULL
                                  CHECK (operacion_pendiente IN ('cambio','baja')),
                              ADD COLUMN IF NOT EXISTS cambios_pendientes JSONB NULL;
ALTER TABLE curso             ADD COLUMN IF NOT EXISTS horas_teoria SMALLINT NOT NULL DEFAULT 0
                                  CHECK (horas_teoria BETWEEN 0 AND 10),
                              ADD COLUMN IF NOT EXISTS horas_practica SMALLINT NOT NULL DEFAULT 0
                                  CHECK (horas_practica BETWEEN 0 AND 10),
                              ADD COLUMN IF NOT EXISTS descripcion VARCHAR(500) NULL;
ALTER TABLE documento_oficial ADD COLUMN IF NOT EXISTS titulo VARCHAR(200) NULL;
ALTER TABLE consulta_contacto ADD COLUMN IF NOT EXISTS fecha_clasificacion TIMESTAMP NULL;

CREATE INDEX IF NOT EXISTS ix_bitacora_actor    ON bitacora_acceso(id_usuario_actor);
CREATE INDEX IF NOT EXISTS ix_solicitud_objetivo ON solicitud_acceso(id_usuario_objetivo);

-- ---------- Restricciones nuevas (las demas de 3.5 ya existen en 01_tablas.sql) ----------
DO $$
DECLARE
    t TEXT;
BEGIN
    -- bitacora_acceso.accion: ampliar a los valores de 3.6 (reemplaza el CHECK de 01).
    ALTER TABLE bitacora_acceso DROP CONSTRAINT IF EXISTS bitacora_acceso_accion_check;
    ALTER TABLE bitacora_acceso DROP CONSTRAINT IF EXISTS ck_bitacora_accion;
    ALTER TABLE bitacora_acceso ADD CONSTRAINT ck_bitacora_accion CHECK (accion IN (
        'alta','cambio_rol','baja','recuperacion','denegado',
        'inicio_sesion','cierre_sesion','acceso_fallido','cambio_contrasena','edicion_datos'));

    -- encuadre de la fotografia del docente (0..100)
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_encuadre' AND conrelid = to_regclass('docente')) THEN
        ALTER TABLE docente ADD CONSTRAINT ck_encuadre
            CHECK (encuadre_x BETWEEN 0 AND 100 AND encuadre_y BETWEEN 0 AND 100);
    END IF;

    -- revisor distinto del editor en las cinco tablas revisables
    FOREACH t IN ARRAY ARRAY['publicacion','docente','plan_estudios','documento_oficial','campana_admision'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_' || t || '_revisor' AND conrelid = to_regclass(t)) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I CHECK (id_director_revisa IS NULL OR id_director_revisa <> id_editor)',
                           t, 'ck_' || t || '_revisor');
        END IF;
    END LOOP;
END $$;

